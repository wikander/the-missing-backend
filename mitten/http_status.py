# All codes above, in ascending order.
HTTP_STATUS_CODES: tuple[int, ...] = tuple(sorted(HTTP_STATUS_PHRASES))

# Besides 1xx, the status codes whose responses have no content (RFC 9110).
BODYLESS_STATUS_CODES: frozenset[int] = frozenset({204, 205, 304})

# The codes a statusCode prefix (4, 40) picks from. 1xx codes are left out:
# they aren't final responses, and a mocked 101 would break the client.
RANDOM_STATUS_CODES: tuple[int, ...] = tuple(c for c in HTTP_STATUS_CODES if c >= 200)
